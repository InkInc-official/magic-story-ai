export type SemanticLabelCategory = keyof typeof AI_SEMANTIC_LABELS;

export function describeSemanticLabel(category: SemanticLabelCategory, value: string): string {
  const labels = AI_SEMANTIC_LABELS[category] as Readonly<Record<string, string>>;
  return labels[value] ?? `ユーザー定義値「${value}」として、その表記と意図を保持する`;
}

export function formatSemanticLabel(category: SemanticLabelCategory, value: string): string {
  return `${value}：${describeSemanticLabel(category, value)}`;
}
